#!/usr/bin/env node
// loomstack build — compiles the spec grammar into sharded megaprompt output.
//
//   node packages/compiler/src/build.mjs [--out dist] [--lines 827] [--domains 24]
//
// Emits:
//   dist/shards/<nn>-<domain>.md   one shard per domain, each safely under 50 MB
//   dist/manifest.json             shard index the router reads at agent runtime
//   dist/SHA256SUMS                per-shard digests for third party verification
//   dist/stats.json                line and byte totals, the record claim itself

import { createWriteStream } from 'node:fs';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { once } from 'node:events';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { DOMAINS, MODULES, ENTITY_ROOTS, entityName } from '../../../specs/grammar/taxonomy.mjs';
import { expandEntity, expandInvariants } from './expand.mjs';

const ROOT = path.resolve(fileURLToPath(import.meta.url), '../../../..');

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : process.argv[i + 1];
}

const OUT = path.resolve(ROOT, arg('out', 'dist'));
const LINES_PER_ENTITY = Number(arg('lines', 827));
const DOMAIN_COUNT = Number(arg('domains', DOMAINS.length));

async function main() {
  const started = Date.now();
  await rm(OUT, { recursive: true, force: true });
  await mkdir(path.join(OUT, 'shards'), { recursive: true });

  const shards = [];
  let totalLines = 0;
  let totalBytes = 0;
  let seq = 0;

  for (let d = 0; d < DOMAIN_COUNT; d += 1) {
    const domain = DOMAINS[d];
    const file = `${String(d + 1).padStart(2, '0')}-${domain.id}.md`;
    const abs = path.join(OUT, 'shards', file);
    const hash = createHash('sha256');
    const stream = createWriteStream(abs);
    let shardLines = 0;
    let shardBytes = 0;

    const write = async (chunk) => {
      hash.update(chunk);
      shardBytes += Buffer.byteLength(chunk);
      if (!stream.write(chunk)) await once(stream, 'drain');
    };

    const header = [
      `# Loomstack shard ${d + 1}: ${domain.label}`,
      `<!-- generated by loomstack build; do not edit by hand -->`,
      `- shard-id: ${domain.id}`,
      `- intent: ${domain.tone}`,
      '',
    ];
    shardLines += header.length;
    await write(`${header.join('\n')}\n`);

    for (const moduleId of MODULES) {
      for (let r = 0; r < ENTITY_ROOTS.length; r += 1) {
        const entity = entityName(moduleId, ENTITY_ROOTS[r], 0);
        seq += 1;
        const base = expandEntity(domain, moduleId, entity, seq);
        const fill = expandInvariants(domain, moduleId, entity, LINES_PER_ENTITY - base.length, seq);
        const block = base.concat(fill);
        shardLines += block.length;
        await write(`${block.join('\n')}\n`);
      }
    }

    stream.end();
    await once(stream, 'finish');
    shards.push({ file, domain: domain.id, lines: shardLines, bytes: shardBytes, sha256: hash.digest('hex') });
    totalLines += shardLines;
    totalBytes += shardBytes;
    process.stdout.write(`  ${file}  ${shardLines.toLocaleString()} lines  ${(shardBytes / 1e6).toFixed(1)} MB\n`);
  }

  const stats = {
    generatedAt: new Date().toISOString(),
    totalLines,
    totalBytes,
    avgLineChars: Number((totalBytes / totalLines).toFixed(2)),
    entities: seq,
    linesPerEntity: LINES_PER_ENTITY,
    shards: shards.length,
    buildSeconds: Number(((Date.now() - started) / 1000).toFixed(1)),
  };

  await writeFile(path.join(OUT, 'manifest.json'), `${JSON.stringify({ version: 1, stats, shards }, null, 2)}\n`);
  await writeFile(path.join(OUT, 'stats.json'), `${JSON.stringify(stats, null, 2)}\n`);
  await writeFile(path.join(OUT, 'SHA256SUMS'), `${shards.map((s) => `${s.sha256}  shards/${s.file}`).join('\n')}\n`);

  process.stdout.write(`\n${totalLines.toLocaleString()} lines / ${(totalBytes / 1e6).toFixed(1)} MB / ${stats.avgLineChars} chars per line / ${stats.buildSeconds}s\n`);
}

main().catch((err) => { console.error(err); process.exit(1); });
