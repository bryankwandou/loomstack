#!/usr/bin/env node
// loomstack ddl — compiles the same grammar the corpus comes from into runnable
// Postgres.
//
// This is the argument against the corpus being decorative. The field lists,
// indexes, state enums and row level security policies in dist/ are not prose
// about a system; they are the same source that produces the schema below.
//
// Everything lands in one database. Isolation comes from one Postgres schema
// per domain, so commerce.core_request and health.core_request coexist without
// colliding and without a prefix convention nobody enforces.
//
//   node packages/compiler/src/ddl.mjs                 # print to stdout
//   node packages/compiler/src/ddl.mjs --modules core  # limit which modules
//   node packages/compiler/src/ddl.mjs --out db/schema.sql

import { writeFile } from 'node:fs/promises';
import { DOMAINS, MODULES, ENTITY_ROOTS, STATES, entityName } from '../../../specs/grammar/taxonomy.mjs';

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : process.argv[i + 1];
}

const only = arg('modules', 'core').split(',').map((s) => s.trim());
const modules = MODULES.filter((m) => only.includes('all') || only.includes(m));
const out = [];
const w = (s = '') => out.push(s);

w('-- Generated by loomstack ddl. Do not edit by hand.');
w('-- Regenerate with: npm run ddl');
w('-- One database, one schema per domain, no cross-domain name collisions.');
w();
w('create extension if not exists pgcrypto;');
w();
w('-- Shared enum, referenced by every entity in every schema.');
w('do $$ begin');
w(`  create type public.entity_status as enum (${STATES.map((s) => `'${s}'`).join(', ')});`);
w('exception when duplicate_object then null; end $$;');
w();
w('-- Tenancy root. Row level security on every entity keys off this table.');
w('create table if not exists public.tenant (');
w('  id          uuid primary key default gen_random_uuid(),');
w('  slug        text not null unique,');
w('  region      text not null default \'ap-southeast-1\',');
w('  created_at  timestamptz not null default now()');
w(');');
w();
w('create or replace function public.touch_updated_at() returns trigger as $$');
w('begin');
w('  new.updated_at = now();');
w('  new.version = old.version + 1;');
w('  return new;');
w('end $$ language plpgsql;');
w();

let tables = 0;

for (const domain of DOMAINS) {
  w(`-- ${'='.repeat(72)}`);
  w(`-- ${domain.label}: ${domain.tone}`);
  w(`-- ${'='.repeat(72)}`);
  w(`create schema if not exists ${domain.id};`);
  w();

  for (const moduleId of modules) {
    for (const root of ENTITY_ROOTS) {
      const entity = entityName(moduleId, root, 0);
      const t = `${domain.id}.${entity}`;
      tables += 1;

      w(`create table if not exists ${t} (`);
      w('  id               uuid primary key default gen_random_uuid(),');
      w('  tenant_id        uuid not null references public.tenant(id) on delete restrict,');
      w('  status           public.entity_status not null default \'draft\',');
      w('  label            text not null check (char_length(label) <= 120),');
      w('  amount_minor     bigint not null default 0,');
      w('  currency         char(3) not null default \'IDR\',');
      w('  metadata         jsonb not null default \'{}\'::jsonb check (pg_column_size(metadata) <= 16384),');
      w('  version          integer not null default 1,');
      w('  idempotency_key  text,');
      w('  trace_id         text,');
      w('  region           text,');
      w('  checksum         bytea,');
      w('  created_by       uuid,');
      w('  created_at       timestamptz not null default now(),');
      w('  updated_at       timestamptz not null default now(),');
      w('  deleted_at       timestamptz');
      w(');');

      // Indexes mirror the `#### indexes` block the corpus emits for this entity.
      w(`create unique index if not exists ${entity}_idem_uq on ${t} (tenant_id, idempotency_key) where deleted_at is null;`);
      w(`create index if not exists ${entity}_status_ix on ${t} (tenant_id, status, created_at desc);`);
      w(`create index if not exists ${entity}_updated_ix on ${t} (tenant_id, updated_at desc);`);
      w(`create index if not exists ${entity}_meta_ix on ${t} using gin (metadata jsonb_path_ops);`);
      w(`create index if not exists ${entity}_pending_ix on ${t} (tenant_id) where status = 'pending';`);

      // Optimistic locking, enforced in the database rather than trusted to callers.
      w(`drop trigger if exists ${entity}_touch on ${t};`);
      w(`create trigger ${entity}_touch before update on ${t} for each row execute function public.touch_updated_at();`);

      // Tenant isolation, enforced by the database rather than by every query.
      w(`alter table ${t} enable row level security;`);
      w(`drop policy if exists ${entity}_tenant_isolation on ${t};`);
      w(`create policy ${entity}_tenant_isolation on ${t}`);
      w(`  using (tenant_id = nullif(current_setting('app.tenant', true), '')::uuid);`);
      w();
    }
  }
}

w(`-- ${tables} tables across ${DOMAINS.length} schemas, modules: ${modules.join(', ')}`);

const sql = `${out.join('\n')}\n`;
const target = arg('out', null);
if (target) {
  await writeFile(target, sql);
  console.error(`wrote ${target}: ${tables} tables, ${DOMAINS.length} schemas, ${sql.split('\n').length} lines`);
} else {
  process.stdout.write(sql);
}
